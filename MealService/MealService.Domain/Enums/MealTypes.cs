namespace MealPlanner.MealService.Domain.Enums;

/// <summary>
/// Represents a set of predefined meal types for categorizing meals in the meal planning application. This 
/// enumeration provides a standardized way to classify meals based on their typical consumption times, 
/// facilitating organization and filtering of meal data. The MealTypes enum includes common meal categories 
/// such as Breakfast, Lunch, and Dinner, allowing for clear identification and management of meals within the system.
/// </summary>
public enum MealTypes
{
    Breakfast,
    Lunch,
    Dinner
}