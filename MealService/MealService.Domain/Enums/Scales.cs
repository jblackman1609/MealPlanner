namespace MealPlanner.MealService.Enums;

/// <summary>
/// Represents a set of predefined scales for measuring ingredients in recipes. This enumeration provides a standardized 
/// way to specify the units of measurement for ingredients, facilitating consistency and clarity in recipe representation. 
/// The Scales enum includes common measurement units such as Gram, Kilogram, Milliliter, Liter, Teaspoon, Tablespoon, Cup, 
/// and Piece, allowing for precise quantification of ingredients in various culinary contexts.
/// </summary>
public enum Scales
{
    Gram,
    Kilogram,
    Milliliter,
    Liter,
    Teaspoon,
    Tablespoon,
    Cup,
    Piece
}